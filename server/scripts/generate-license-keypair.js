import fs from "fs";
import path from "path";
import crypto from "crypto";
import { fileURLToPath } from "url";

// One-time (or key-rotation) setup: generates the Ed25519 keypair that backs
// enterprise license keys. The private key never leaves this machine — it's
// written to a gitignored file and used only by scripts/sign-license.js to
// issue licenses. The public key is meant to ship with the OSS codebase (it
// can only verify signatures, not create them), so it's written straight into
// config/licensePublicKey.js.
//
// Usage: node server/scripts/generate-license-keypair.js
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const privateKeyPath = path.join(__dirname, "..", ".license-private-key.pem");

if (fs.existsSync(privateKeyPath)) {
  console.error(
    `refusing to overwrite existing private key at ${privateKeyPath} — ` +
      "delete it first if you really intend to rotate keys (this invalidates every license issued with the old key)."
  );
  process.exit(1);
}

const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519", {
  publicKeyEncoding: { type: "spki", format: "pem" },
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
});

fs.writeFileSync(privateKeyPath, privateKey, { mode: 0o600 });

const publicKeyModule = `// Auto-generated by scripts/generate-license-keypair.js — safe to commit,
// this is a PUBLIC key, it can only verify license signatures, not create them.
export const LICENSE_PUBLIC_KEY = \`${publicKey.trim()}\`;
`;
fs.writeFileSync(path.join(__dirname, "..", "config", "licensePublicKey.js"), publicKeyModule);

console.log(`private key written to ${privateKeyPath} (keep this off the OSS repo, back it up somewhere safe)`);
console.log("public key written to server/config/licensePublicKey.js (safe to commit)");
